def test_schema7_adoption_and_reopen_keep_completed_measurements(tmp_path: Path) -> None:
    from wb_tool.api import (
        FigureLayoutStyle,
        WBAnalysisProject,
        WBLayoutProject,
        analysis_is_current,
        initial_composition,
        with_figure_layout,
    )

    base, paths = configured(tmp_path)
    base, results = complete(base, paths)
    before = fill_project_table(base, results)
    assert [cell.value for cell in before] == [4000, None, 0, 8000, 16000, 0, None, None]
    layout = with_figure_layout(base, initial_composition(base), FigureLayoutStyle(heading_size=12))
    # Change only display ordering and split the first original row into two explicit segments.
    parts = list(layout.composition.slices)
    first = parts.pop(0)
    parts.extend(
        (
            first.model_copy(update={"last_lane": 1}),
            first.model_copy(update={"first_lane": 2, "position": 2}),
        )
    )
    layout = layout.model_copy(
        update={"composition": layout.composition.model_copy(update={"slices": tuple(parts)})}
    )
    saved = tmp_path / "layout.json"
    saved.write_bytes(layout.model_dump_json().encode())
    reopened = read_figure_project(saved.read_bytes())
    assert isinstance(reopened, WBLayoutProject)
    assert reopened == layout and reopened.schema_version == 7
    assert reopened.analyses == base.analyses and reopened.rows == base.rows
    assert all(analysis_is_current(reopened, plan) for plan in reopened.analyses)
    after = fill_project_table(reopened, results)
    # v6+ exposes origin labels explicitly; v3 kept those display columns empty.
    assert [cell.evidence_origin for cell in after] == ["本机运行"] * 6 + ["", ""]
    assert tuple(replace(cell, evidence_origin="") for cell in after) == before
    with pytest.raises(ValueError):
        WBAnalysisProject.from_bytes(saved.read_bytes())
    # A failed legacy reader cannot rewrite the source document.
    assert saved.read_bytes() == layout.model_dump_json().encode()


def test_schema7_archive_restore_keeps_measurement_ocr_and_normalization_identity(
    tmp_path: Path,
) -> None:
    from wb_tool.api import (
        FigureLayoutStyle,
        WBLayoutProject,
        initial_composition,
        read_project_result,
        restore_staged_project,
        with_figure_layout,
    )

    from tools.wb.tests.test_archive_restore import real_bundle
    from tools.wb.tests.test_project_analysis import asset

    base, sources, evidence, results = real_bundle(tmp_path)
    project = with_figure_layout(
        base, initial_composition(base), FigureLayoutStyle(heading_size=12)
    )
    archive = tmp_path / "scientific-layout.zip"
    export_figure_bundle(project, sources, str(archive), runs=evidence)
    assert inspect_project_archive(str(archive)) == project
    staged = stage_project_archive(str(archive), str(tmp_path / "stage"))
    copied = tuple(
        asset(Path(item.path).read_bytes(), f"local-{index}")
        for index, item in enumerate(staged.assets)
    )
    restored = restore_staged_project(staged, copied, asset(archive.read_bytes(), "archive"))
    assert isinstance(restored, WBLayoutProject)
    assert read_figure_project(restored.model_dump_json().encode()) == restored
    assert restored.composition == project.composition
    assert restored.normalizations == project.normalizations
    assert restored.ocr is not None and project.ocr is not None
    assert restored.ocr.rows == project.ocr.rows and restored.ocr.run == project.ocr.run
    assert restored.analyses == project.analyses
    assert len(restored.imported_runs) == 3
    result_bytes = {item.sha256: Path(item.path).read_bytes() for item in staged.assets}
    verified = tuple(
        read_project_result(plan, result_bytes[plan.run.result.sha256])
        for plan in restored.analyses
        if plan.run is not None and plan.run.result is not None
    )
    before = fill_project_table(project, results)
    after = fill_project_table(restored, verified)
    assert [cell.evidence_origin for cell in after] == ["归档历史证据"] * 6
    assert {cell.archive_sha256 for cell in after} == {staged.archive_sha256}
    assert tuple(replace(cell, evidence_origin="", archive_sha256="") for cell in after) == tuple(
        replace(cell, evidence_origin="", archive_sha256="") for cell in before
    )
    local_sources = tuple(FigureSourcePath(item.sha256, item.path) for item in staged.assets)
    assert render_figure(restored, local_sources).rgb == render_figure(project, sources).rgb
