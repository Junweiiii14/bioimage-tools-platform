def legacy_project(
    tmp_path: Path, version: int
) -> tuple[WBFigureProject, tuple[FigureSourcePath, ...]]:
    base, sources = sample(tmp_path)
    raw = base.model_dump(mode="json")
    raw["schema_version"] = version
    if version >= 2:
        raw["suggestions"] = []
    if version >= 3:
        raw["analyses"] = []
    if version >= 4:
        row = base.rows[0]
        assert row.source is not None
        raw["ocr"] = {
            "source": row.source.model_dump(mode="json"),
            "filename": row.filename,
            "width": row.width,
            "height": row.height,
            "run": None,
            "recognition": None,
            "rows": [],
        }
    if version >= 5:
        raw["normalizations"] = []
    if version >= 6:
        # Historical ZIPs are retained as opaque evidence, never recursively unpacked.
        # A deterministic valid empty ZIP avoids using any private experimental data.
        stream = BytesIO()
        with ZipFile(stream, "w"):
            pass
        data = stream.getvalue()
        historical = tmp_path / "historical.zip"
        historical.write_bytes(data)
        archive = AssetRef(
            asset_id="historical",
            relative_path="inputs/historical.zip",
            sha256=sha256(data).hexdigest(),
            size_bytes=len(data),
        )
        raw["archive_sources"] = [
            {
                "archive": archive.model_dump(mode="json"),
                "project_id": base.project_id,
                "revision": base.revision,
                "format_version": 1,
            }
        ]
        raw["imported_runs"] = []
        sources += (FigureSourcePath(archive.sha256, str(historical)),)
    return read_figure_project(json.dumps(raw).encode()), sources


@pytest.mark.parametrize("version", range(1, 7))
def test_legacy_schema_save_render_and_archive_match_old_renderer(
    tmp_path: Path, version: int
) -> None:
    project, sources = legacy_project(tmp_path, version)
    raw = project.model_dump_json().encode()
    reopened = read_figure_project(raw)
    assert type(reopened) is type(project) and reopened == project
    assert reopened.schema_version == version
    assert b'"composition"' not in raw and b'"layout_style"' not in raw
    rendered = render_figure(reopened, sources)
    assert (rendered.width, rendered.height) == (356, 166)
    assert sha256(rendered.rgb).hexdigest() == LEGACY_RGB_SHA256
    assert sha256(rendered.manifest_json.encode()).hexdigest() == LEGACY_MANIFEST_SHA256[version]
    archive = tmp_path / "legacy.zip"
    export_figure_bundle(reopened, sources, str(archive))
    assert inspect_project_archive(str(archive)) == project
    with ZipFile(archive) as zipped:
        assert zipped.read("manifest.json") == rendered.manifest_json.encode()
        assert read_figure_project(zipped.read("project.json")) == project
    staged = stage_project_archive(str(archive), str(tmp_path / "stage"))
    assert staged.project == project
    assert Path(staged.archive_path).read_bytes() == archive.read_bytes()


